create table users (
    id bigint generated by default as identity primary key,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    role varchar(16) not null check (role in ('STUDENT', 'STAFF'))
);

create table sessions (
    id bigint generated by default as identity primary key,
    start_date date not null,
    end_date date not null,
    capacity integer not null check (capacity > 0),
    booked_count integer not null check (booked_count between 0 and capacity),
    check (end_date >= start_date)
);

create table booking_requests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    session_id bigint not null references sessions(id),
    status varchar(16) not null check (status in ('PENDING', 'APPROVED', 'REJECTED')),
    is_paid boolean not null,
    comment varchar(2048),
    created_at timestamp not null,
    unique (user_id, session_id),
    check (not is_paid or status = 'APPROVED')
);

create table documents (
    id bigint generated by default as identity primary key,
    request_id bigint not null references booking_requests(id),
    file_name varchar(255) not null,
    file_path varchar(255) not null unique
);

create index documents_request_id_idx on documents(request_id);
